#!/usr/bin/env python3

import os
import re
import shutil
import getopt
import sys

from pathlib import Path



def usage():
    print(sys.argv[0] + ' [OPTION]')
    print('    -h, --help                  print this message')
    print('    -w, --workspace_root        workspace directory')
    print('    -l, --leaves                leaf list from the stage 0 reader: "<name> <first word>" per')
    print('                                  leaf, in term order')
    print('    -p, --tree_only             write only the leaf table (tree_data.cpp, tree.cmake)')



def read_leaf_list(filename):
    leaves = []
    names = set()
    for line_number, line in enumerate(Path(filename).read_bytes().split(b'\n'), 1):
        if len(line) == 0:
            continue
        where = str(filename) + ': line ' + str(line_number)
        name, space, first = line.partition(b' ')
        if not space or len(first) == 0:
            sys.exit(where + ': expected a leaf name and its first word')
        name = name.decode('latin-1')
        if not re.fullmatch(r'[A-Za-z0-9_]+', name):
            sys.exit(where + ': leaf name "' + name + '" is not letters, digits and underscores')
        if name in names:
            sys.exit(where + ': leaf name "' + name + '" appears twice')
        names.add(name)
        leaves.append((name, first))
    if len(leaves) == 0:
        sys.exit(str(filename) + ': no leaves')
    return leaves



def c_string(word):
    text = ''
    for b in word:
        if 32 <= b < 127 and chr(b) not in '"\\?':
            text += chr(b)
        else:
            text += '\\%03o' % b
    return '"' + text + '"'



def write_from_template(template, template_text, name, destination):
    text = template_text.replace('aoeu', name).replace('snth', name)
    with open(destination, 'w') as f:
        f.write(text)
    shutil.copymode(template, destination)



def write_if_changed(filename, text):
    if filename.exists() and filename.read_text() == text:
        return
    filename.write_text(text)



def prepare_leaves(workspace_root, tree_only, leaf_list):
    leaves = read_leaf_list(leaf_list)

    generated_include = workspace_root / 'generated_include'
    generated_src = workspace_root / 'generated_src'
    generated_symbols = generated_include / 'matchmaker' / 'generated_symbols'

    if not tree_only:
        for location in [generated_symbols, generated_src]:
            shutil.rmtree(location, ignore_errors=True)
            os.makedirs(location)

        matchmaker_root = Path(os.path.dirname(os.path.realpath(__file__))).parent
        templates = {}
        for template_name in ['internal_interface.h', 'leaf.cpp']:
            template = matchmaker_root / 'templates' / template_name
            templates[template_name] = (template, template.read_text())

        for name, _ in leaves:
            os.makedirs(generated_symbols / name)
            write_from_template(*templates['internal_interface.h'], name,
                                generated_symbols / name / (name + '.h'))
            write_from_template(*templates['leaf.cpp'], name, generated_src / (name + '.cpp'))

    tree_data = '// generated by scripts/generate_code.py from the stage 0 leaf list\n\n'
    tree_data += '#include <tree.h>\n\n'
    tree_data += ''.join('MM_DECLARE_LEAF(' + name + ')\n' for name, _ in leaves)
    tree_data += '\nnamespace tree\n{\n    extern Leaf const leaves[] = {\n'
    tree_data += ''.join('        MM_LEAF(' + name + '),\n' for name, _ in leaves)
    tree_data += '    };\n\n    extern char const * const first_terms[] = {\n'
    tree_data += ''.join('        ' + c_string(first) + ',\n' for _, first in leaves)
    tree_data += '    };\n\n    extern int const leaf_count = ' + str(len(leaves)) + ';\n}\n'
    os.makedirs(generated_src, exist_ok=True)
    write_if_changed(generated_src / 'tree_data.cpp', tree_data)

    tree_cmake = '# generated by scripts/generate_code.py from the stage 0 leaf list\n\n'
    tree_cmake += 'set(matchmaker_srcs generated_src/tree_data.cpp)\n\n'
    tree_cmake += 'set(\n    prefix_list\n' + ''.join('    ' + name + '\n' for name, _ in leaves) + ')\n'
    write_if_changed(workspace_root / 'tree.cmake', tree_cmake)



def main():
    try:
        opts, args = getopt.getopt(sys.argv[1:], 'hw:l:p',
                                   ['help', 'workspace_root=', 'leaves=', 'tree_only'])
    except getopt.GetoptError as err:
        print(err)
        usage()
        sys.exit(2)

    workspace_root = ''
    tree_only = False
    leaf_list = None

    for o, a in opts:
        if o in ('-h', '--help'):
            usage()
            sys.exit()
        elif o in ('-w', '--workspace_root'):
            workspace_root = a
        elif o in ('-l', '--leaves'):
            leaf_list = a
        elif o in ('-p', '--tree_only'):
            tree_only = True
        else:
            assert False, "unhandled option"

    if workspace_root == '':
        print("workspace_root unset, use -w to set a workspace directory")
        usage()
        sys.exit(2)
    if leaf_list is None:
        print("a leaf list is required, use -l to name one")
        usage()
        sys.exit(2)

    prepare_leaves(Path(workspace_root), tree_only, leaf_list)
    exit(0)



if __name__ == "__main__":
    main()
